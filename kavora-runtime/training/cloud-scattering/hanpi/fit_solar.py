"""Fit and validate the directional and upper-hemisphere sources."""

import argparse
import copy
import json
from pathlib import Path
import sys

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from neural.feature_layout import feature_names
from neural.model import MultiScatterMLP
from pack_weights import pack_weights


def dataset(files, device, channel="sun"):
    xs, ys = [], []
    for path in files:
        with np.load(path) as data:
            prefix = "" if channel == "sun" else "sky_"
            xs.append(data[prefix + "features"])
            ys.append(data[prefix + "source"])
    return tuple(torch.tensor(np.concatenate(arrays), device=device) for arrays in (xs, ys))


def export_interpolator(files, out):
    """Fit the varying part of the response to inputs already evaluated by each ray."""
    coefficients = []
    for layer in (0, 1):
        features, source = dataset(files[layer::2], "cpu")
        rho, trans, mu = features[:, 0].numpy(), features[:, 4].numpy(), features[:, 7].numpy()
        basis = np.column_stack((np.ones_like(rho), rho, np.sqrt(rho), trans, rho * trans, trans * trans))
        design = np.column_stack((basis, mu[:, None] * basis))
        # A constant cancels between the lattice and the ray sample.
        coeff = np.linalg.lstsq(design.astype(np.float64), source.numpy(), rcond=None)[0].reshape(2, 6)
        coefficients.append(coeff[:, 1:])
    with out.open("w", encoding="utf-8", newline="\n") as shader:
        shader.write(
            "// SPDX-License-Identifier: MIT\n// Generated by training/cloud-scattering/hanpi/fit_solar.py.\n"
            "module cloud_source_interpolation;\n\n"
            "public float cloudSourceVariation(uint layer, float density, float transmission, float cosine)\n{\n"
        )
        for i, name in enumerate(
            ("densityWeight", "rootWeight", "beamWeight", "crossWeight", "squareWeight")
        ):
            pairs = ["float2(" + ", ".join(f"{v:.9g}f" for v in c[:, i]) + ")" for c in coefficients]
            shader.write(f"  const float2 {name} = layer == 0 ? {pairs[0]} : {pairs[1]};\n")
        shader.write(
            "  const float2 value = density * (densityWeight + transmission * crossWeight)\n"
            "    + sqrt(max(density, 0.0f)) * rootWeight + transmission * (beamWeight + transmission * squareWeight);\n"
            "  return value.x + cosine * value.y;\n}\n"
        )


def fit_channel(files, device, channel, activation, smoke):
    torch.manual_seed(3321)
    x, y = dataset(files[:8], device, channel)
    val, reference = dataset(files[8:10], device, channel)
    model = MultiScatterMLP(len(feature_names(channel)), hidden=96, layers=4, activation=activation).to(device)
    model.set_feature_norm(x.mean(0).cpu().numpy(), x.std(0).cpu().numpy())
    optimizer = torch.optim.AdamW(model.parameters(), lr=0.002, weight_decay=0.0001)
    iterations = 2 if smoke else 3600
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, iterations, eta_min=0.0001)
    best = float("inf")
    for step in range(1, iterations + 1):
        ids = torch.randint(len(x), (512,), device=device)
        target = y[ids]
        predicted = model(x[ids]).ravel()
        # The variance of the path estimate grows with the expected source.
        # Detaching the variance weight retains the conditional mean as target.
        scale = (0.02 + predicted.detach()).sqrt()
        loss = ((predicted - target).square() / scale).mean()
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()
        scheduler.step()
        if step % 100 == 0 or step == iterations:
            with torch.no_grad():
                error = (model(val).ravel() - reference).abs().mean().item()
            if error < best:
                best = error
                selected = copy.deepcopy(model.state_dict())
    model.load_state_dict(selected)
    model.cpu()
    metrics = {}
    with torch.no_grad():
        for path in files[-2:]:
            x, y = dataset([path], "cpu", channel)
            p = model(x).ravel()
            cosine = x[:, 7] if channel == "sun" else x[:, 6]
            for name, mask in (
                ("all", torch.ones_like(y, dtype=torch.bool)),
                ("forward", cosine > .99),
                ("backscatter", cosine < -.75),
            ):
                if mask.any():
                    metrics[f"{path.stem}/{name}"] = {
                        "count": int(mask.sum()),
                        "reference": y[mask].mean().item(),
                        "prediction": p[mask].mean().item(),
                        "mae": (p[mask] - y[mask]).abs().mean().item(),
                    }
    return model, metrics


def fit(labels, out, device, activation, smoke=False):
    out.mkdir(parents=True, exist_ok=True)
    files = sorted(labels.glob("region-*.npz"))
    if len(files) != 12:
        raise ValueError("Expected six independent regions of both cloud layers")
    metrics = {}
    for channel in ("sun", "sky"):
        model, metrics[channel] = fit_channel(files, device, channel, activation, smoke)
        model.export_numpy(out / f"{channel}.npz", feature_names(channel))
    pack_weights(out / "sun.npz", out / "sky.npz", out / "cloud_neural_lighting.bin", activation)
    export_interpolator(files[:8], out / "cloud_source_interpolation.slang")
    report = json.dumps(metrics, indent=2)
    (out / "validation.json").write_text(report + "\n", encoding="utf-8")
    print(report, flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("labels", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--activation", choices=("silu", "leaky_relu"), default="leaky_relu")
    parser.add_argument("--smoke", action="store_true")
    args = parser.parse_args()
    fit(args.labels, args.out, args.device, args.activation, args.smoke)
